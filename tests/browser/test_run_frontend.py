def test_stale_approval_does_not_replay_after_refresh(page, ui_url, run_repository):
    run = advance(run_repository, RunState.AwaitingApproval, Risk.SIDE_EFFECT)
    restore(page, ui_url, run.to_dict())
    requests = []

    def stale(route):
        requests.append(route.request.post_data_json)
        fulfill(route, {"run_id": run.run_id, "error": {"code": "STALE_RUN_VERSION"}}, 409)

    page.route("**/approval", stale)
    page.locator("#approve-run").click()
    expect(page.locator("#run-error-code")).to_have_text("STALE_RUN_VERSION")
    expect(page.locator("#reject-run")).to_be_disabled()
    page.evaluate("document.getElementById('reject-run').click()")
    approved = run_repository.decide_approval(
        run.run_id, ApprovalDecisionRequest(ApprovalChoice.APPROVE, 4)
    ).to_dict()
    page.route("**/api/runs/" + run.run_id, lambda route: fulfill(route, approved))
    page.locator("#refresh-run").click()
    expect(page.locator("#run-state")).to_have_text("Approved")
    assert len(requests) == 1


def test_refresh_is_get_and_locks_decisions_until_confirmed(page, ui_url, run_repository):
    run = advance(run_repository, RunState.AwaitingApproval, Risk.SIDE_EFFECT).to_dict()
    restore(page, ui_url, run)
    pending = []
    page.route("**/api/runs/" + run["run_id"], lambda route: pending.append(route))
    with page.expect_request("**/api/runs/" + run["run_id"]):
        page.locator("#refresh-run").click()
    expect(page.locator("#run-status")).to_have_text("Refreshing Run…")
    expect(page.locator("#approve-run")).to_be_disabled()
    expect(page.locator("#reject-run")).to_be_disabled()
    expect(page.locator("#create-run")).to_be_disabled()
    assert pending[0].request.method == "GET" and pending[0].request.post_data is None
    fulfill(pending[0], {"error": {"code": "DATABASE_UNAVAILABLE"}}, 503)
    expect(page.locator("#run-error-code")).to_have_text("DATABASE_UNAVAILABLE")
    expect(page.locator("#run-state")).to_have_text("AwaitingApproval")
    expect(page.locator("#run-version")).to_have_text("4")
    expect(page.locator("#approve-run")).to_be_disabled()


