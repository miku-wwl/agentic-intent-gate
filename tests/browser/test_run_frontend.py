"""Prompt 3 DOM/unit lane: controlled HTTP responses, NOT backend E2E proof.

Public Run examples are generated by the real repository contract helpers.
The separate test_run_ui_e2e module never intercepts backend responses.
"""

import json

import pytest
from playwright.sync_api import expect
from run_helpers import advance

from agentic_intent_gate.domain.approval import ApprovalChoice, ApprovalDecisionRequest
from agentic_intent_gate.domain.contracts import Risk
