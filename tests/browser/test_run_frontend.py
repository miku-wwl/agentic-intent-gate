pytestmark = [pytest.mark.browser, pytest.mark.frontend]


def fulfill(route, body, status=200):
    route.fulfill(status=status, content_type="application/json", body=json.dumps(body))


def restore(page, ui_url, run):
    page.route("**/api/runs/" + run["run_id"], lambda route: fulfill(route, run))
    assert page.goto(ui_url + "?run_id=" + run["run_id"]).status == 200
    expect(page.locator("#run-state")).to_have_text(run["state"])


@pytest.mark.parametrize("state", list(RunState))
def test_all_eight_server_states_render_explicit_fields(page, ui_url, run_repository, state):
    risk = (
        Risk.SIDE_EFFECT
        if state in {RunState.AwaitingApproval, RunState.Approved, RunState.Rejected}
        else Risk.READ_ONLY
    )
    run = advance(run_repository, state, risk).to_dict()
    restore(page, ui_url, run)
    for field, value in (
        ("run-id", run["run_id"]),
        ("run-version", str(run["version"])),
        ("run-created", run["created_at"]),
        ("run-updated", run["updated_at"]),
        ("run-original-intent", run["intent"]["text"]),
    ):
        expect(page.locator("#" + field)).to_have_text(value)
    if run["plan"] is not None:
        expect(page.locator("#run-plan")).to_be_visible()
        expect(page.locator("#run-risk")).to_have_text(run["risk_class"])
        expect(page.locator("#run-approval-required")).to_have_text(
            str(run["approval_required"]).lower()
        )
    else:
        expect(page.locator("#run-plan")).to_be_hidden()
        expect(page.locator("#run-approval-required")).to_have_text("Not yet known")
    if state == RunState.AwaitingApproval:
        expect(page.locator("#approve-run")).to_be_enabled()
        expect(page.locator("#reject-run")).to_be_enabled()
    else:
        expect(page.locator("#approve-run")).to_be_hidden()
        expect(page.locator("#reject-run")).to_be_disabled()
    if state in {RunState.Approved, RunState.Rejected}:
        expect(page.locator("#approval-summary")).to_contain_text("No tools executed")
        expect(page.locator("#run-approval-required")).to_have_text("true")
    if state == RunState.PlanRejected:
        expect(page.locator("#run-plan-error")).to_be_visible()
        expect(page.locator("#run-plan-error-code")).to_have_text("MODEL_TIMEOUT")
    else:
        expect(page.locator("#run-plan-error")).to_be_hidden()


@pytest.mark.parametrize("reason", ["", "  ", "Reviewed 😀\n"])
def test_approval_version_and_blank_omission_contract(page, ui_url, run_repository, reason):
    run = advance(run_repository, RunState.AwaitingApproval, Risk.SIDE_EFFECT)
    restore(page, ui_url, run.to_dict())
    approved = run_repository.decide_approval(
        run.run_id, ApprovalDecisionRequest(ApprovalChoice.APPROVE, run.version)
    ).to_dict()
    requests = []

    def reply(route):
        requests.append(route.request.post_data_json)
        fulfill(route, approved)

    page.route("**/approval", reply)
    page.locator("#approval-reason").fill(reason)
    page.locator("#approve-run").click()
    expect(page.locator("#run-state")).to_have_text("Approved")
    expected = {"decision": "APPROVE", "expected_version": run.version}
    if reason != "":
        expected["reason"] = reason
    assert requests == [expected]
    assert "reason" not in requests[0] if reason == "" else requests[0]["reason"] == reason


@pytest.mark.parametrize(
    "code,status",
    [
        ("INVALID_INTENT", 400),
        ("INVALID_APPROVAL", 400),
        ("RUN_NOT_FOUND", 404),
        ("STALE_RUN_VERSION", 409),
        ("INVALID_RUN_TRANSITION", 409),
        ("REQUEST_TOO_LARGE", 413),
        ("UNSUPPORTED_MEDIA_TYPE", 415),
        ("DATABASE_UNAVAILABLE", 503),
        ("INTERNAL_ERROR", 500),
    ],
)
def test_safe_error_envelope_codes_ignore_raw_diagnostics(page, ui_url, code, status):
    page.route(
        "**/api/runs",
        lambda route: fulfill(
            route,
            {"run_id": None, "error": {"code": code, "message": "private SQL traceback C:/secret"}},
            status,
        ),
    )
    assert page.goto(ui_url).status == 200
    page.locator("#run-intent").fill("Read service-demo")
    page.locator("#create-run").click()
    expect(page.locator("#run-error-code")).to_have_text(code)
    expect(page.locator("#run-error")).to_be_visible()
    expect(page.locator("#run-details")).to_be_hidden()
    expect(page.locator("body")).not_to_contain_text("private SQL traceback")
    expect(page.locator("#create-run")).to_be_enabled()


@pytest.mark.parametrize("kind", ["network", "nonjson", "bad-success", "unknown-error"])
def test_uncertain_failures_never_fabricate_a_run(page, ui_url, kind):
    def reply(route):
        if kind == "network":
            route.abort("failed")
        elif kind == "nonjson":
            route.fulfill(status=502, content_type="text/html", body="private server traceback")
        elif kind == "bad-success":
            fulfill(route, {"run_id": "not-a-run", "state": "Approved"}, 201)
        else:
            fulfill(route, {"error": {"code": {"toString": "private"}}}, 500)

    page.route("**/api/runs", reply)
    assert page.goto(ui_url).status == 200
    page.locator("#run-intent").fill("Read service-demo")
    page.locator("#create-run").click()
    expect(page.locator("#run-error-code")).to_have_text(
        "NETWORK_ERROR" if kind == "network" else "UNEXPECTED_RESPONSE"
    )
    expect(page.locator("#run-details")).to_be_hidden()
    expect(page.locator("#create-run")).to_be_enabled()
    expect(page.locator("body")).not_to_contain_text("private server traceback")


