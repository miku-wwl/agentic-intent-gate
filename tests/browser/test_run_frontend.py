def test_invalid_reason_does_not_submit_or_change_run(page, ui_url, run_repository):
    run = advance(run_repository, RunState.AwaitingApproval, Risk.SIDE_EFFECT).to_dict()
    restore(page, ui_url, run)
    requests = []
    page.route("**/approval", lambda route: requests.append(route))
    reason = page.locator("#approval-reason")
    reason.evaluate(
        """(node, value) => {
            node.value = value;
            node.dispatchEvent(new Event("input", {bubbles: true}));
        }""",
        "😀" * 1025,
    )
    # Native fill enforces maxlength in UTF-16 units; inject the actual boundary case.
    assert reason.evaluate("node => [...node.value].length") == 1025
    assert reason.evaluate("node => node.value.length") == 2050
    page.locator("#approve-run").click()
    expect(page.locator("#run-error-code")).to_have_text("INVALID_APPROVAL")
    expect(page.locator("#run-version")).to_have_text("4")
    assert not requests


@pytest.mark.parametrize(
    "attack",
    [
        "<script>alert(1)</script>",
        "<img src=x onerror=alert(1)>",
        "javascript:alert(1)",
        "</textarea><script>window.attack=1</script>",
    ],
)
def test_hostile_display_strings_are_inert_text(page, ui_url, run_repository, attack):
    run = advance(run_repository, RunState.AwaitingApproval, Risk.SIDE_EFFECT).to_dict()
    run["intent"]["text"] = attack
    run["plan"]["goal"] = attack
    run["plan"]["steps"][0]["arguments"]["note"] = attack
    dialogs = []
    page.on("dialog", lambda dialog: (dialogs.append(dialog.message), dialog.dismiss()))
    restore(page, ui_url, run)
    expect(page.locator("#run-original-intent")).to_have_text(attack)
    expect(page.locator("#run-goal")).to_have_text(attack)
    assert json.loads(page.locator("#run-steps pre").text_content())["note"] == attack
    assert not dialogs and page.evaluate("window.attack ?? null") is None
    assert (
        page.locator("#run-details script, #run-plan script, #run-plan img, #run-plan a").count()
        == 0
    )


def test_keyboard_labels_focus_and_status_accessibility(page, ui_url, run_repository):
    run = advance(run_repository).to_dict()
    page.route("**/api/runs", lambda route: fulfill(route, run, 201))
    assert page.goto(ui_url).status == 200
    expect(page.get_by_role("heading", level=1)).to_have_count(1)
    expect(page.get_by_label("Run intent", exact=True)).to_be_visible()
    expect(page.locator("#run-status")).to_have_attribute("aria-live", "polite")
    page.locator("#run-intent").fill(" Read service-demo\n")
    page.locator("#run-intent").press("Tab")
    expect(page.locator("#create-run")).to_be_focused()
    assert (
        page.locator("#create-run").evaluate("node => getComputedStyle(node).outlineWidth") == "3px"
    )
    with page.expect_request("**/api/runs") as pending:
        page.locator("#create-run").press("Enter")
    assert pending.value.post_data_json == {"text": " Read service-demo\n"}
    expect(page.locator("#run-details")).to_be_focused()


